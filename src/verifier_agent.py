    result = call_verifier(
        architecture_problem="We need to add a new feature to a legacy Rails monolith from a new Django service.",
        architecture_decision="Use Django's pre_init/post_init signals to hook into model construction instead of overriding the constructor.",
        generated_dr="Signals are the officially recommended extension point in Django and avoid fragile constructor overriding. This approach also automatically scales to handle millions of requests per second with zero configuration.",
        prompt_variant="few_shot",
        include_context=True,
        request_id="smoke_test",
    )
    print(json.dumps(result.arguments, indent=2, ensure_ascii=False))
    print("Aggregated counts:", aggregate_counts(result.arguments))
    print("Resolved model version:", result.resolved_model_version)
    if result.error:
        print("ERROR:", result.error)
